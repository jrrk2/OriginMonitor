#!/usr/bin/env python3
"""Pack the Pickles (1998) stellar spectral library into StarSpectra.hpp, the star spectra the live stacker's Gaia colour calibration predicts with.

    tools/pickles_pack.py --pickles DIR --passbands FILE [--out StarSpectra.hpp]

DIR holds pickles_uk.fits and pickles_uk_1..131.fits, from STScI:
    https://archive.stsci.edu/hlsps/reference-atlases/cdbs/grid/pickles/dat_uvk/
FILE is passband.dat of the Gaia (E)DR3 passbands (Riello et al. 2021), from ESA:
    https://www.cosmos.esa.int/web/gaia/edr3-passbands  (GaiaEDR3_passbands_zeropoints.zip)

Two sequences of solar-metallicity templates are written, dwarfs (V) and giants (III), each sorted by its synthetic Gaia BP-RP: photon counts through
the BP and RP passbands, zero point set so that A0V has BP-RP 0 (Gaia's magnitudes are Vega-based). Each spectrum is stored 380..720 nm in 2 nm bins as
photons per nm (the flux times the wavelength, the bin's mean), normalised to a mean of 1: only its shape matters to a colour.
"""
import argparse, os
import numpy as np
from astropy.io import fits

LO, HI, STEP = 380, 720, 2


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--pickles", required=True)
    ap.add_argument("--passbands", required=True)
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "StarSpectra.hpp"))
    a = ap.parse_args()
    pb = np.loadtxt(a.passbands)
    wl, bp, rp = pb[:, 0], np.where(pb[:, 3] > 99, 0, pb[:, 3]), np.where(pb[:, 5] > 99, 0, pb[:, 5])
    edges = np.arange(LO - STEP / 2, HI + STEP, STEP)
    seqs = {"V": [], "III": []}
    zero = None
    for fn, sp in fits.open(os.path.join(a.pickles, "pickles_uk.fits"))[1].data:
        fn, sp = fn.strip(), sp.strip()
        cls = "V" if sp.endswith("V") and not sp.endswith("IV") else "III" if sp.endswith("III") else None
        d = fits.open(os.path.join(a.pickles, fn + ".fits"))[1].data
        lam, f = d["WAVELENGTH"] / 10.0, d["FLUX"]
        F = np.interp(wl, lam, f)
        c = -2.5 * np.log10(np.trapezoid(F * wl * bp, wl) / np.trapezoid(F * wl * rp, wl))
        if sp == "A0V": zero = c
        if cls is None or sp[0] in "wr": continue                  # luminosity classes V and III, solar metallicity only
        fine = np.arange(LO - STEP / 2, HI + STEP / 2 + 0.1, 0.1)
        ph = np.interp(fine, lam, f) * fine                      # photons per unit wavelength
        bins = np.array([ph[(fine >= edges[i]) & (fine < edges[i + 1])].mean() for i in range(len(edges) - 1)])
        seqs[cls].append((sp, c, bins / bins.mean()))
    with open(a.out, "w") as o:
        o.write("// StarSpectra.hpp - generated by tools/pickles_pack.py: do not edit.\n"
                "// Pickles (1998, PASP 110, 863) stellar spectral library, solar-metallicity dwarfs (V) and giants (III), as distributed by STScI, each with its synthetic\n"
                "// Gaia BP-RP through the Gaia (E)DR3 passbands (Riello et al. 2021, A&A 649, A3; ESA/Gaia/DPAC), A0V = 0. Spectra: photons per nm, %d..%d nm in %d nm bins,\n"
                "// mean 1.\n#ifndef STARSPECTRA_H\n#define STARSPECTRA_H\n\n" % (LO, HI, STEP))
        o.write("struct StarSpectrum { const char* type; float bpRp; float photons[%d]; };\n\n" % (len(edges) - 1))
        for cls, name in (("V", "kDwarfSpectra"), ("III", "kGiantSpectra")):
            s = sorted(seqs[cls], key=lambda t: t[1] - zero)
            o.write("static const StarSpectrum %s[%d] = {\n" % (name, len(s)))
            for sp, c, b in s:
                o.write('    {"%s", %.4ff, {%s}},\n' % (sp, c - zero, ", ".join("%.4g" % v for v in b)))
            o.write("};\n\n")
        o.write("#endif\n")
    for cls in seqs: print(cls, len(seqs[cls]), "templates:", " ".join("%s %.2f" % (sp, c - zero) for sp, c, _ in sorted(seqs[cls], key=lambda t: t[1])))
    print("->", a.out)


if __name__ == "__main__":
    main()
